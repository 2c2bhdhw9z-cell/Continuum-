//! Opt-in: a host build of BlastEm with Continuum's patches, loaded as a shared library through the
//! real frontend (`NativeLibretroCore`), the same entry points the app uses on the phone.
//! `BLASTEM_SO=path/to/blastem_libretro.so`; without it every test here says it was skipped and
//! passes, so CI does not run them. Build it from the pinned source with the patches applied in the
//! order `scripts/build-core.sh` applies them, then
//! `make -f Makefile.libretro core CORE_ARGS="NEW_CORE=1 NOLTO=1"` (the generated 68K and Z80
//! cores, the ones the iPhone build uses).
//!
//! Every cartridge here is generated by the test itself: a header and a few 68K instructions.
#![cfg(feature = "native-core")]

use std::path::{Path, PathBuf};

use emulator_bridge::cores::native_core::NativeLibretroCore;
use emulator_bridge::cores::{ContentHint, CoreDescriptor, EmulatorCore};
use emulator_bridge::frame::{FrameGeometry, PixelFormat};
use emulator_bridge::memory::{MEMORY_SAVE_RAM, MEMORY_SYSTEM_RAM};

/// BlastEm's descriptor, as the app declares it (`CoreCatalog.blastem` in ContinuumApp.swift).
fn descriptor(so: &str) -> CoreDescriptor {
    CoreDescriptor {
        id: "blastem".into(),
        display_name: "BlastEm".into(),
        systems: vec!["genesis".into(), "segacd".into(), "sega32x".into()],
        geometry: FrameGeometry { base_width: 320, base_height: 224, max_width: 352, max_height: 480, aspect_ratio: 4.0 / 3.0 },
        target_fps: 59.9227,
        audio_sample_rate: 53267,
        pixel_format: PixelFormat::Xrgb8888,
        module_url: so.to_string(),
        priority: 0,
    }
}

fn library() -> Option<String> {
    let so = std::env::var("BLASTEM_SO").ok();
    if so.is_none() {
        eprintln!("BLASTEM_SO not set: skipped");
    }
    so
}

/// A folder of its own for one test: the system and save folder, as on the phone (one folder).
fn folder(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("continuum-blastem-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// A fresh copy of the library for each load: the core keeps state in globals, so two tests (or
/// two loads) never share one, like two launches on the phone.
fn load(so: &str, dir: &Path, game: &Path) -> NativeLibretroCore {
    static LOADS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let copy = dir.join(format!(
        "blastem-{}-{}.so",
        game.file_stem().unwrap().to_string_lossy(),
        LOADS.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    let _ = std::fs::copy(so, &copy);
    let mut core =
        unsafe { NativeLibretroCore::load(descriptor(so), &copy, dir.to_str(), dir.to_str()) }.expect("the core loads");
    let mut hint = ContentHint::from_filename(game.to_str().unwrap());
    hint.full_path = game.to_str().map(str::to_string);
    core.load_content(&[], &hint).unwrap_or_else(|e| {
        panic!("{} did not load: {e} ({})", game.display(), emulator_bridge::cores::native_core::last_core_log_line())
    });
    core
}

fn run(core: &mut NativeLibretroCore, frames: u32) {
    let input = emulator_bridge::input::InputState::default().snapshot();
    for _ in 0..frames {
        core.run_frame(&input).unwrap();
    }
}

/// A Mega Drive cartridge of `size` bytes: the header with `product` as its product code, the
/// stack at the top of work RAM, and `code` at $200, where the reset vector points.
fn cartridge(size: usize, product: &str, code: &[u8]) -> Vec<u8> {
    let mut rom = vec![0u8; size];
    rom[0..4].copy_from_slice(&0x00FF_FE00u32.to_be_bytes());
    rom[4..8].copy_from_slice(&0x0000_0200u32.to_be_bytes());
    rom[0x100..0x110].copy_from_slice(b"SEGA MEGA DRIVE ");
    let serial = format!("GM {product:<8} -00");
    rom[0x180..0x180 + serial.len()].copy_from_slice(serial.as_bytes());
    rom[0x1A0..0x1A8].copy_from_slice(&[0, 0, 0, 0, 0, (size >> 16) as u8 - 1, 0xFF, 0xFF]);
    rom[0x1F0] = b'U';
    rom[0x200..0x200 + code.len()].copy_from_slice(code);
    rom
}

/// `move.l (address).l,d0`, `move.l d0,($FF0000).l`, then `bra.s *`.
fn read_long_into_ram(address: u32) -> Vec<u8> {
    let mut code = vec![0x20, 0x39];
    code.extend(address.to_be_bytes());
    code.extend([0x23, 0xC0, 0x00, 0xFF, 0x00, 0x00, 0x60, 0xFE]);
    code
}

/// The first long of work RAM, which BlastEm keeps as host-order 16-bit words.
fn first_ram_long(core: &NativeLibretroCore) -> u32 {
    let ram = core.memory_region(MEMORY_SYSTEM_RAM).expect("work RAM");
    let hi = u16::from_ne_bytes([ram[0], ram[1]]);
    let lo = u16::from_ne_bytes([ram[2], ram[3]]);
    u32::from(hi) << 16 | u32::from(lo)
}

/// The cartridge list (`blastem-cartridge-saves.patch`) as BlastEm itself reads it: BlastEm
/// parses the whole list on every cartridge load and stops on a broken entry, so a load at all
/// is the first proof. Then the entries it finds by product code get the save hardware the list
/// gives them, and NFL Quarterback Club's last megabyte, which the list did not map before, now
/// reads back the ROM's own bytes.
#[test]
fn the_patched_cartridge_list_is_what_blastem_reads() {
    let Some(so) = library() else { return };
    let dir = folder("rom-db");
    let check = |name: &str, product: &str, size: usize, code: &[u8], magic_at: Option<usize>| -> (usize, u32) {
        let mut rom = cartridge(size, product, code);
        if let Some(at) = magic_at {
            rom[at..at + 4].copy_from_slice(&0x1234_5678u32.to_be_bytes());
        }
        let path = dir.join(format!("{name}.md"));
        std::fs::write(&path, rom).unwrap();
        let mut core = load(&so, &dir, &path);
        run(&mut core, 10);
        let save = core.memory_region(MEMORY_SAVE_RAM).map_or(0, <[u8]>::len);
        (save, first_ram_long(&core))
    };
    // Not in the list: the header has no save, so there is none.
    assert_eq!(check("plain", "00000000", 0x2_0000, &[0x60, 0xFE], None).0, 0);
    // Sega's X24C01 (Greatest Heavyweights), the Codemasters board (Micro Machines 2), the
    // Acclaim 32 Mbit board (NFL Quarterback Club): each the EEPROM size the list gives it.
    assert_eq!(check("ghw", "MK-1228", 0x20_0000, &[0x60, 0xFE], None).0, 128);
    assert_eq!(check("mm2", "T-120096", 0x10_0000, &[0x60, 0xFE], None).0, 2048);
    let (nfl_save, nfl_read) =
        check("nfl", "T-081276", 0x40_0000, &read_long_into_ram(0x3F_FFF0), Some(0x3F_FFF0));
    assert_eq!(nfl_save, 256);
    assert_eq!(nfl_read, 0x1234_5678, "NFL Quarterback Club's last megabyte is not the ROM's: {nfl_read:#010X}");
    let _ = std::fs::remove_dir_all(dir);
}

/// A word of the 32X's SDRAM, which BlastEm publishes in its memory map at $06000000 as host-order
/// 16-bit words.
fn sdram_word(core: &NativeLibretroCore, offset: usize) -> u16 {
    let sdram = core
        .memory_map()
        .iter()
        .find(|d| d.start == 0x0600_0000)
        .expect("the 32X's SDRAM in the memory map");
    assert!(sdram.ptr != 0 && offset + 2 <= sdram.len);
    let bytes = unsafe { std::slice::from_raw_parts((sdram.ptr + offset) as *const u8, 2) };
    u16::from_ne_bytes([bytes[0], bytes[1]])
}

/// How many different colours the last frame has: a stopped 32X shows one (black) or a few.
fn colours(core: &NativeLibretroCore) -> usize {
    let video = core.video().expect("a frame");
    let mut seen = std::collections::HashSet::new();
    for y in 0..video.height as usize {
        let row = &video.data[y * video.stride_bytes..][..video.width as usize * 4];
        for px in row.chunks_exact(4) {
            seen.insert(u32::from_ne_bytes([px[0], px[1], px[2], px[3]]));
        }
    }
    seen.len()
}

/// The last frame as a PPM in BLASTEM_OUT, when it is set, for a person to look at.
fn keep_frame(core: &NativeLibretroCore, name: &str) {
    let Ok(out) = std::env::var("BLASTEM_OUT") else { return };
    let video = core.video().expect("a frame");
    let mut ppm = format!("P6 {} {} 255\n", video.width, video.height).into_bytes();
    for y in 0..video.height as usize {
        for x in 0..video.width as usize {
            let o = y * video.stride_bytes + x * 4;
            ppm.extend_from_slice(&[video.data[o + 2], video.data[o + 1], video.data[o]]);
        }
    }
    std::fs::create_dir_all(&out).unwrap();
    std::fs::write(Path::new(&out).join(format!("{name}.ppm")), ppm).unwrap();
}

/// The .32x games in `BLASTEM_32X_DIR`, each copied into `dir`: (name, copy, the file's bytes).
/// None when the variable is not set. The test does not ship them; fetch them yourself, for example
/// the 32X port of the 240p Test Suite (GPL-2.0, github.com/Dasutin/32X240pTestSuite, release
/// v1.0) and HexGL 32X (MIT, github.com/haroldo-ok/hexgl-32x, release v0.0.1).
fn games_32x(dir: &Path) -> Option<Vec<(String, PathBuf, Vec<u8>)>> {
    let Ok(games) = std::env::var("BLASTEM_32X_DIR") else {
        eprintln!("BLASTEM_32X_DIR not set: the 32X start-up test was skipped");
        return None;
    };
    let mut found = Vec::new();
    for entry in std::fs::read_dir(&games).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().and_then(|e| e.to_str()) != Some("32x") {
            continue;
        }
        let game = dir.join(path.file_name().unwrap());
        std::fs::copy(&path, &game).unwrap();
        let name = path.file_stem().unwrap().to_string_lossy().into_owned();
        found.push((name, game, std::fs::read(&path).unwrap()));
    }
    found.sort();
    assert!(!found.is_empty(), "no .32x file in {games}");
    Some(found)
}

/// Continuum's own 32X start-up code (`blastem-32x-startup.patch`) starting real 32X homebrew
/// with no 32X start-up files anywhere (see `games_32x` for the games). Each must load, have its
/// SH-2 program in SDRAM where its header asks (for a game that copies one), and be drawing a
/// picture of many colours after a few seconds, which it cannot do unless both SH-2s were started
/// and the Mega Drive side got its handshake (`a_players_own_32x_files_come_first` shows the same
/// games staying dark when the SH-2s never start).
#[test]
fn a_32x_game_starts_with_no_32x_files() {
    let Some(so) = library() else { return };
    let dir = folder("32x");
    let Some(games) = games_32x(&dir) else { return };
    for name in ["32X_M_BIOS.bin", "32X_S_BIOS.bin", "32X_G_BIOS.bin"] {
        assert!(!dir.join(name).exists());
    }
    for (name, game, rom) in games {
        let mut core = load(&so, &dir, &game);
        // The header's initial data load ($3D4 source, $3D8 destination, $3DC length).
        let be32 = |at: usize| u32::from_be_bytes(rom[at..at + 4].try_into().unwrap());
        let (src, dst, len) = (be32(0x3D4) as usize & 0x3F_FFFC, be32(0x3D8) as usize & 0x3_FFFC, be32(0x3DC) as usize);
        run(&mut core, 300);
        if len >= 4 {
            for at in (0..len.min(64)).step_by(2) {
                let want = u16::from_be_bytes([rom[src + at], rom[src + at + 1]]);
                assert_eq!(sdram_word(&core, dst + at), want, "{name}: SDRAM +{:#X}", dst + at);
            }
        }
        let early = colours(&core);
        keep_frame(&core, &format!("{name}-300"));
        run(&mut core, 300);
        let later = colours(&core);
        keep_frame(&core, &format!("{name}-600"));
        eprintln!("{name}: {early} colours at 5 s, {later} at 10 s");
        assert!(early.max(later) >= 8, "{name} is not drawing anything: {early} and {later} colours");
    }
    let _ = std::fs::remove_dir_all(dir);
}

/// The player's own pair of 32X start-up files wins over Continuum's code; an empty placeholder
/// counts as no file, and so does a pair with one missing, which starts on Continuum's pair rather
/// than one of each (`sh2_bios_usable` in libblastem.c and `continuum_read_boot_file` in 32x.c
/// agree). The player's files here are stand-ins that never hand over (their reset vector points at
/// a branch to itself), so a game started on them must stay dark: that is also what shows the
/// picture in `a_32x_game_starts_with_no_32x_files` comes from SH-2s that really were started.
#[test]
fn a_players_own_32x_files_come_first() {
    let Some(so) = library() else { return };
    let dir = folder("32x-own");
    let Some(games) = games_32x(&dir) else { return };
    // PC $00000008 and SP $0603F000, then `bra .` and `nop` at $8, as the SH-2 reads them.
    let stuck: &[u8] = &[0, 0, 0, 8, 0x06, 0x03, 0xF0, 0, 0xAF, 0xFE, 0x00, 0x09];
    // (32X_M_BIOS.bin, 32X_S_BIOS.bin, whether the game starts); None is no file at all.
    type Case<'a> = (Option<&'a [u8]>, Option<&'a [u8]>, bool);
    let cases: [Case; 4] = [
        (Some(&[]), Some(&[]), true),
        (Some(stuck), None, true),
        (None, Some(stuck), true),
        (Some(stuck), Some(stuck), false),
    ];
    for (main, sub, starts) in cases {
        for (name, bytes) in [("32X_M_BIOS.bin", main), ("32X_S_BIOS.bin", sub)] {
            let _ = std::fs::remove_file(dir.join(name));
            if let Some(bytes) = bytes {
                std::fs::write(dir.join(name), bytes).unwrap();
            }
        }
        let size = |b: Option<&[u8]>| b.map_or("no".to_string(), |b| format!("a {}-byte", b.len()));
        for (name, game, _) in &games {
            let mut core = load(&so, &dir, game);
            run(&mut core, 600);
            let seen = colours(&core);
            eprintln!("{name} with {} main and {} sub start-up file: {seen} colours at 10 s", size(main), size(sub));
            if starts {
                assert!(seen >= 8, "{name} did not start ({} main, {} sub file): {seen} colours", size(main), size(sub));
            } else {
                assert!(seen <= 2, "{name} drew {seen} colours on start-up files that never hand over");
            }
        }
    }
    let _ = std::fs::remove_dir_all(dir);
}
