//! Opt-in: a host build of BlastEm with Continuum's patches, loaded as a shared library through the
//! real frontend (`NativeLibretroCore`), the same entry points the app uses on the phone.
//! `BLASTEM_SO=path/to/blastem_libretro.so`; without it every test here says it was skipped and
//! passes, so CI does not run them. Build it from the pinned source with the patches applied in the
//! order `scripts/build-core.sh` applies them, then
//! `make -f Makefile.libretro core CORE_ARGS="NEW_CORE=1 NOLTO=1"` (the generated 68K and Z80
//! cores, the ones the iPhone build uses).
//!
//! Every cartridge here is generated by the test itself: a header and a few 68K instructions.
#![cfg(feature = "native-core")]

use std::path::{Path, PathBuf};

use emulator_bridge::cores::native_core::NativeLibretroCore;
use emulator_bridge::cores::{ContentHint, CoreDescriptor, EmulatorCore};
use emulator_bridge::frame::{FrameGeometry, PixelFormat};
use emulator_bridge::memory::{MEMORY_SAVE_RAM, MEMORY_SYSTEM_RAM};

/// BlastEm's descriptor, as the app declares it (`CoreCatalog.blastem` in ContinuumApp.swift).
fn descriptor(so: &str) -> CoreDescriptor {
    CoreDescriptor {
        id: "blastem".into(),
        display_name: "BlastEm".into(),
        systems: vec!["genesis".into(), "segacd".into(), "sega32x".into()],
        geometry: FrameGeometry { base_width: 320, base_height: 224, max_width: 352, max_height: 480, aspect_ratio: 4.0 / 3.0 },
        target_fps: 59.9227,
        audio_sample_rate: 53267,
        pixel_format: PixelFormat::Xrgb8888,
        module_url: so.to_string(),
        priority: 0,
    }
}

fn library() -> Option<String> {
    let so = std::env::var("BLASTEM_SO").ok();
    if so.is_none() {
        eprintln!("BLASTEM_SO not set: skipped");
    }
    so
}

/// A folder of its own for one test: the system and save folder, as on the phone (one folder).
fn folder(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("continuum-blastem-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// A fresh copy of the library for each load: the core keeps state in globals, so two tests (or
/// two loads) never share one, like two launches on the phone.
fn load(so: &str, dir: &Path, game: &Path) -> NativeLibretroCore {
    static LOADS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let copy = dir.join(format!(
        "blastem-{}-{}.so",
        game.file_stem().unwrap().to_string_lossy(),
        LOADS.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    let _ = std::fs::copy(so, &copy);
    let mut core =
        unsafe { NativeLibretroCore::load(descriptor(so), &copy, dir.to_str(), dir.to_str()) }.expect("the core loads");
    let mut hint = ContentHint::from_filename(game.to_str().unwrap());
    hint.full_path = game.to_str().map(str::to_string);
    core.load_content(&[], &hint).unwrap_or_else(|e| {
        panic!("{} did not load: {e} ({})", game.display(), emulator_bridge::cores::native_core::last_core_log_line())
    });
    core
}

fn run(core: &mut NativeLibretroCore, frames: u32) {
    let input = emulator_bridge::input::InputState::default().snapshot();
    for _ in 0..frames {
        core.run_frame(&input).unwrap();
    }
}

/// A Mega Drive cartridge of `size` bytes: the header with `product` as its product code, the
/// stack at the top of work RAM, and `code` at $200, where the reset vector points.
fn cartridge(size: usize, product: &str, code: &[u8]) -> Vec<u8> {
    let mut rom = vec![0u8; size];
    rom[0..4].copy_from_slice(&0x00FF_FE00u32.to_be_bytes());
    rom[4..8].copy_from_slice(&0x0000_0200u32.to_be_bytes());
    rom[0x100..0x110].copy_from_slice(b"SEGA MEGA DRIVE ");
    let serial = format!("GM {product:<8} -00");
    rom[0x180..0x180 + serial.len()].copy_from_slice(serial.as_bytes());
    rom[0x1A0..0x1A8].copy_from_slice(&[0, 0, 0, 0, 0, (size >> 16) as u8 - 1, 0xFF, 0xFF]);
    rom[0x1F0] = b'U';
    rom[0x200..0x200 + code.len()].copy_from_slice(code);
    rom
}

/// `move.l (address).l,d0`, `move.l d0,($FF0000).l`, then `bra.s *`.
fn read_long_into_ram(address: u32) -> Vec<u8> {
    let mut code = vec![0x20, 0x39];
    code.extend(address.to_be_bytes());
    code.extend([0x23, 0xC0, 0x00, 0xFF, 0x00, 0x00, 0x60, 0xFE]);
    code
}

/// The first long of work RAM, which BlastEm keeps as host-order 16-bit words.
fn first_ram_long(core: &NativeLibretroCore) -> u32 {
    let ram = core.memory_region(MEMORY_SYSTEM_RAM).expect("work RAM");
    let hi = u16::from_ne_bytes([ram[0], ram[1]]);
    let lo = u16::from_ne_bytes([ram[2], ram[3]]);
    u32::from(hi) << 16 | u32::from(lo)
}

/// The cartridge list (`blastem-cartridge-saves.patch`) as BlastEm itself reads it: BlastEm
/// parses the whole list on every cartridge load and stops on a broken entry, so a load at all
/// is the first proof. Then the entries it finds by product code get the save hardware the list
/// gives them, and NFL Quarterback Club's last megabyte, which the list did not map before, now
/// reads back the ROM's own bytes.
#[test]
fn the_patched_cartridge_list_is_what_blastem_reads() {
    let Some(so) = library() else { return };
    let dir = folder("rom-db");
    let mut check = |name: &str, product: &str, size: usize, code: &[u8], magic_at: Option<usize>| -> (usize, u32) {
        let mut rom = cartridge(size, product, code);
        if let Some(at) = magic_at {
            rom[at..at + 4].copy_from_slice(&0x1234_5678u32.to_be_bytes());
        }
        let path = dir.join(format!("{name}.md"));
        std::fs::write(&path, rom).unwrap();
        let mut core = load(&so, &dir, &path);
        run(&mut core, 10);
        let save = core.memory_region(MEMORY_SAVE_RAM).map_or(0, <[u8]>::len);
        (save, first_ram_long(&core))
    };
    // Not in the list: the header has no save, so there is none.
    assert_eq!(check("plain", "00000000", 0x2_0000, &[0x60, 0xFE], None).0, 0);
    // Sega's X24C01 (Greatest Heavyweights), the Codemasters board (Micro Machines 2), the
    // Acclaim 32 Mbit board (NFL Quarterback Club): each the EEPROM size the list gives it.
    assert_eq!(check("ghw", "MK-1228", 0x20_0000, &[0x60, 0xFE], None).0, 128);
    assert_eq!(check("mm2", "T-120096", 0x10_0000, &[0x60, 0xFE], None).0, 2048);
    let (nfl_save, nfl_read) =
        check("nfl", "T-081276", 0x40_0000, &read_long_into_ram(0x3F_FFF0), Some(0x3F_FFF0));
    assert_eq!(nfl_save, 256);
    assert_eq!(nfl_read, 0x1234_5678, "NFL Quarterback Club's last megabyte is not the ROM's: {nfl_read:#010X}");
    let _ = std::fs::remove_dir_all(dir);
}
