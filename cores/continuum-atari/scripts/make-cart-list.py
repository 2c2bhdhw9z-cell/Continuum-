#!/usr/bin/env python3
"""Writes src/cart_list.rs, cAtari's list of known 7800 cartridges, from MAME's software list for
the 7800 (hash/a7800.xml, which MAME publishes under CC0-1.0: free of any licence).

A headerless cartridge file (.bin, or an .a78 without its 128-byte header) says nothing about how
its chips are wired, so cAtari finds it here by the CRC-32 of its contents: the board (bank
switching, POKEY, RAM), whether it is a PAL game, and the controller it wants.

    python3 scripts/make-cart-list.py /path/to/mame/hash/a7800.xml
"""

import os
import sys
import xml.etree.ElementTree as ET

KINDS = {
    "a78_rom": "Rom",
    "a78_pokey": "RomPokey",
    "a78_sg": "Sg",
    "a78_sg_pokey": "SgPokey",
    "a78_sg_ram": "SgRam",
    "a78_sg9": "Sg9",
    "a78_mram": "Mram",
    "a78_abs": "Absolute",
    "a78_act": "Activision",
    "a78_hsc": "Rom",  # the High Score Cartridge itself: never a game
    "a78_xboard": "XBoard",
    "a78_xm": "Xm",
    "a78_megacart": "MegaCart",
    "a78_versa": "Versa",
    "a78_p450_t0": "RomP450",
    "a78_p450_t1": "RomPokeyP450",
    "a78_p450_t6": "SgRamP450",
    "a78_p450_ta": "Sg9P450",
    "a78_p450_vb": "VersaP450",
}


def main():
    src = sys.argv[1]
    root = ET.parse(src).getroot()
    rows = []
    for sw in root.findall("software"):
        name = sw.get("name")
        desc = sw.findtext("description") or name
        pal = False
        for sf in sw.findall("sharedfeat"):
            if sf.get("name") == "compatibility" and "PAL" in (sf.get("value") or ""):
                pal = True
        for part in sw.findall("part"):
            feats = {f.get("name"): f.get("value") for f in part.findall("feature")}
            slot = feats.get("slot", "a78_rom")
            if slot == "a78_hsc":
                continue
            kind = KINDS.get(slot)
            if kind is None:
                raise SystemExit(f"{name}: unknown slot {slot}")
            gun = feats.get("peripheral") == "lightgun"
            for area in part.findall("dataarea"):
                if area.get("name") != "rom":
                    continue
                roms = area.findall("rom")
                if len(roms) != 1 or roms[0].get("crc") is None:
                    continue
                rom = roms[0]
                size = int(rom.get("size"), 0)
                crc = int(rom.get("crc"), 16)
                rows.append((crc, size, kind, pal, gun, name, desc))
    rows.sort()
    seen = set()
    out = []
    out.append("// Generated by scripts/make-cart-list.py from MAME 0.289's hash/a7800.xml (CC0-1.0).")
    out.append("// Do not edit by hand: run the script again.")
    out.append("")
    out.append("use crate::cart::Kind;")
    out.append("")
    out.append("/// A known cartridge: the CRC-32 and size of its contents (no header), its board, whether")
    out.append("/// it is a PAL game, whether it is played with the light gun, MAME's short name, its title.")
    out.append("pub struct Known {")
    out.append("    pub crc: u32,")
    out.append("    pub size: u32,")
    out.append("    pub kind: Kind,")
    out.append("    pub pal: bool,")
    out.append("    pub light_gun: bool,")
    out.append("    pub name: &'static str,")
    out.append("    pub title: &'static str,")
    out.append("}")
    out.append("")
    out.append("pub static KNOWN: &[Known] = &[")
    for crc, size, kind, pal, gun, name, desc in rows:
        if (crc, size) in seen:
            continue
        seen.add((crc, size))
        title = desc.replace("\\", "\\\\").replace('"', '\\"')
        out.append(
            f'    Known {{ crc: 0x{crc:08x}, size: 0x{size:x}, kind: Kind::{kind}, pal: {str(pal).lower()}, '
            f'light_gun: {str(gun).lower()}, name: "{name}", title: "{title}" }},'
        )
    out.append("];")
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "src", "cart_list.rs")
    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(seen)} cartridges written to src/cart_list.rs")


if __name__ == "__main__":
    main()
