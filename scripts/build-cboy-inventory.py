#!/usr/bin/env python3
"""Builds .kiro/notes/docs/CBOY_OPTIONS_INVENTORY.md from the raw extracted keys (.kiro/notes/docs/option-sources/*.keys,
made by scripts/extract-core-option-keys.sh) and the hand mapping (mapping.tsv). Fails if an
extracted key has no mapping row, a row names a key that was not extracted, or a cboy key in a
row does not exist in cores/continuum-gb/src/options.rs."""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = root / ".kiro/notes/docs/option-sources"
cboy = set(re.findall(r'c"(cboy_[a-z0-9_]+)"', (root / "cores/continuum-gb/src/options.rs").read_text()))
keys = {p.stem: p.read_text().split() for p in sorted(src.glob("*.keys")) if not p.stem.startswith("std_")}
std = {p.stem: p.read_text().splitlines() for p in sorted(src.glob("std_*.keys"))}
commits = {p.stem: p.read_text().split() for p in src.glob("*.commit")}
rows = [l.split("\t") for l in (src / "mapping.tsv").read_text().splitlines() if l and not l.startswith("#")]
mapped = {(r[0], r[1]): r for r in rows}
errors = [f"unmapped: {c} {k}" for c, ks in keys.items() for k in ks if (c, k) not in mapped]
errors += [f"not extracted: {r[0]} {r[1]}" for r in rows if r[1] not in keys.get(r[0], [])]
for r in rows:
    for k in filter(None, (r[3] if len(r) > 3 else "").split(",")):
        if k not in cboy:
            errors.append(f"no such cBoy option: {k} (row {r[1]})")
srows = [l.split("\t") for l in (src / "standalone.tsv").read_text().splitlines() if l and not l.startswith("#")]
where = {}
for c, lines in std.items():
    for l in lines:
        path, _, k = l.rpartition(":") if c != "std_bgb" else ("", "", l)
        where[(c, k)] = path
errors += [f"standalone unmapped: {c} {k}" for (c, k) in where if not any(r[0] == c and r[1] == k for r in srows)]
errors += [f"standalone not extracted: {r[0]} {r[1]}" for r in srows if (r[0], r[1]) not in where]
for r in srows:
    for k in filter(None, r[3].split(",")):
        if k not in cboy:
            errors.append(f"no such cBoy option: {k} (standalone {r[1]})")
if errors:
    sys.exit("\n".join(errors))
standalone = (src / "standalone.md").read_text() if (src / "standalone.md").exists() else ""
out = ["# cBoy options inventory", "",
       "Generated by `scripts/build-cboy-inventory.py` from the keys extracted by",
       "`scripts/extract-core-option-keys.sh` (raw lists in `.kiro/notes/docs/option-sources/*.keys`). Do not edit by hand;",
       "edit `.kiro/notes/docs/option-sources/mapping.tsv` and rerun.", "", "## Sources", "",
       "| Core | Repository | Commit | Keys |", "|---|---|---|---|"]
for c in keys:
    h, url = (commits.get(c, ["?", "?"]) + ["?"])[:2]
    out.append(f"| {c} | {url} | `{h}` | {len(keys[c])} |")
total = sum(len(v) for v in keys.values())
count = lambda s: sum(1 for r in rows if r[2] == s)
out += ["", f"Extracted keys: **{total}**. Covered by cBoy: {count('yes')}. Gaps: {count('gap')}. "
        f"Deliberately not done: {count('no')}. Not applicable: {count('n/a')}. cBoy options: **{len(cboy)}**.", "",
        "## Libretro core options, key by key", "", "| Core | Key | cBoy | cBoy option | Note |", "|---|---|---|---|---|"]
for r in rows:
    r += [""] * (5 - len(r))
    out.append(f"| {r[0]} | `{r[1]}` | {r[2]} | {', '.join('`'+k+'`' for k in r[3].split(',') if k)} | {r[4]} |")
used = {k for r in rows for k in r[3].split(",") if k}
out += ["", "## cBoy options no libretro core above has", "", ", ".join(f"`{k}`" for k in sorted(cboy - used)), ""]
out += ["## Standalone emulators", "",
        "Settings extracted from each program's own source (or, for closed-source BGB, its manual). Each row cites where.",
        "Emulicious is closed source and publishes no settings list (https://emulicious.net/ has none), so it has no rows.", "",
        "| Emulator | Source | Commit |", "|---|---|---|"]
for c in std:
    h, url = (commits.get(c, ["?", "?"]) + ["?"])[:2]
    out.append(f"| {c[4:]} | {url} | `{h}` |")
out += ["", "| Emulator | Setting | cBoy | cBoy option | Note | Cited from |", "|---|---|---|---|---|---|"]
for r in srows:
    r += [""] * (5 - len(r))
    h, url = (commits.get(r[0], ["?", "?"]) + ["?"])[:2]
    path = where[(r[0], r[1])]
    cite = f"{url}/blob/{h}/{path}" if path else url
    out.append(f"| {r[0][4:]} | `{r[1]}` | {r[2]} | {', '.join('`'+k+'`' for k in r[3].split(',') if k)} | {r[4]} | {cite} |")
cnt = lambda st: sum(1 for r in srows if r[2] == st)
out += ["", f"Standalone settings: **{len(srows)}**. In cBoy: {cnt('yes')}. App: {cnt('app')}. Gaps: {cnt('gap')}. Not applicable: {cnt('n/a')}.", ""]
out += [standalone]
(root / ".kiro/notes/docs/CBOY_OPTIONS_INVENTORY.md").write_text("\n".join(out))
print(f"{total} libretro keys, {len(srows)} standalone settings, {len(cboy)} cBoy options")
