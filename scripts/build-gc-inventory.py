#!/usr/bin/env python3
"""Builds .kiro/notes/docs/GC_OPTIONS_INVENTORY.md: every setting of every current GameCube / Wii
emulator, which emulators have it, and what our own core does about it.

Inputs (all in .kiro/notes/docs/option-sources/gc/):
  <source>.keys / .commit  written by scripts/extract-gc-option-keys.py (never by hand)
  names.tsv                Dolphin's setting names and where Dolphin keeps them
  same.tsv                 hand-written: a setting of a non-Dolphin emulator that is the same
                           thing as a Dolphin setting (id TAB Dolphin id)
  mapping.tsv              hand-written: each setting's status in our core
Fails if any extracted setting is not in mapping.tsv, or mapping.tsv names one that no
emulator has.
"""
import collections
import glob
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = os.path.join(ROOT, ".kiro/notes/docs/option-sources/gc")
OUT = os.path.join(ROOT, ".kiro/notes/docs/GC_OPTIONS_INVENTORY.md")

# Column order and short names in the table.
SHORT = [
    ("dolphin", "Dolphin"), ("dolphin_android", "Dolphin Android"), ("libretro", "RetroArch"),
    ("manic", "Manic"), ("dolphinios", "DolphiniOS"), ("icube", "iCube"), ("provenance", "Provenance"),
    ("mmjr2", "MMJR2"), ("mmjr2_android", "MMJR2 Android"), ("slippi", "Slippi"),
    ("primehack", "PrimeHack"), ("mpn", "MPN"), ("ishiiruka", "Ishiiruka"), ("dolphinps4", "DolphinPS4"),
    ("porpoise", "Porpoise"), ("lazuli", "Lazuli"), ("gecko", "gecko"), ("rustcube", "rustcube"),
    ("pureikyubu", "pureikyubu"),
]
CATS = [
    ("system", "System"), ("video", "Picture"), ("audio", "Sound"), ("input", "Controls"),
    ("link", "Link and online"), ("performance", "Performance"), ("debug", "Debug"),
    ("game", "One game's extras"),
]
STATUS = {
    "core": "planned in our core",
    "app": "the app does it",
    "app-gap": "app, to add",
    "na": "does not apply",
}


def tsv(name):
    path = os.path.join(G, name)
    if not os.path.exists(path):
        return []
    return [l.rstrip("\n").split("\t") for l in open(path) if l.strip() and not l.startswith("#")]


def names():
    return {r[0]: r[1] for r in tsv("names.tsv")}


def raw():
    """source -> set of raw ids."""
    out = {}
    for src, _ in SHORT:
        out[src] = {r[0] for r in tsv(f"{src}.keys")}
    return out


def aliases():
    """raw id -> canonical id."""
    infos = names()
    alias = {}
    # RetroArch-style keys: the Dolphin setting the RetroArch core ties each one to.
    for src in ("libretro", "manic"):
        for r in tsv(f"{src}.keys"):
            if r[0] != r[1] and r[0] in infos:
                alias.setdefault(r[1], r[0])
    # Ishiiruka (older Dolphin): the same key name in today's Dolphin, when it is unambiguous.
    by_key = collections.defaultdict(list)
    for i, where in infos.items():
        by_key[where.split("/")[-1].lower()].append(i)
    for r in tsv("ishiiruka.keys"):
        k = r[0][len("ISHIIRUKA_"):].lower()
        if len(by_key.get(k, [])) == 1:
            alias[r[0]] = by_key[k][0]
    for r in tsv("same.tsv"):
        alias[r[0]] = r[1]
    return alias


def canonical():
    """canonical id -> set of sources."""
    alias = aliases()
    have = collections.defaultdict(set)
    for src, ids in raw().items():
        for i in ids:
            have[alias.get(i, i)].add(src)
    return have


def canonical_ids():
    return set(canonical())


def main():
    have = canonical()
    infos = names()
    mapping = {r[0]: (r[1], r[2] if len(r) > 2 else "", r[3] if len(r) > 3 else "") for r in tsv("mapping.tsv")}
    missing = sorted(set(have) - set(mapping))
    extra = sorted(set(mapping) - set(have))
    bad = [i for i, (s, c, _) in mapping.items() if s not in STATUS or (s == "core" and c not in dict(CATS))]
    if missing or extra or bad:
        for i in missing:
            print("not in mapping.tsv:", i, file=sys.stderr)
        for i in extra:
            print("in mapping.tsv but no emulator has it:", i, file=sys.stderr)
        for i in bad:
            print("bad status or category:", i, mapping[i], file=sys.stderr)
        sys.exit(1)

    short = dict(SHORT)
    commits = {}
    for src, _ in SHORT:
        lines = open(os.path.join(G, f"{src}.commit")).read().splitlines()
        commits[src] = lines
    counts = collections.Counter(s for s, _, _ in mapping.values())
    out = []
    w = out.append
    w("# GameCube and Wii settings inventory (our own core)\n")
    w("Generated by `scripts/build-gc-inventory.py` from the settings pulled out of each emulator's")
    w("source by `scripts/extract-gc-option-keys.py`. Do not edit by hand: edit")
    w("`option-sources/gc/mapping.tsv` (and `same.tsv`) and rerun.\n")
    w("Rule (docs/CORE_OPTIONS_STANDARD.md): our core offers every setting any of these offers, and more.")
    w("Settings the app already does for every console (speed, save states, cheats, filters, on-screen")
    w("controls, online play, RetroAchievements) stay in the app, not the core.\n")
    w("## Emulators compared\n")
    w("| Emulator | What it is | Repository | Commit | Settings |")
    w("|---|---|---|---|---|")
    per_src = collections.Counter(s for srcs in have.values() for s in srcs)
    for src, name in SHORT:
        c = commits[src]
        w(f"| {name} | {c[2] if len(c) > 2 else ''} | {c[1]} | `{c[0][:12]}` | {per_src[src]} |")
    w("")
    w(f"Different settings in all: **{len(have)}**. Planned in our core: {counts['core']}. The app does "
      f"it: {counts['app']}. Belongs in the app, not there yet: {counts['app-gap']}. Does not apply on an "
      f"iPhone: {counts['na']}.\n")
    w("Our core does not exist yet, so every \"planned\" row is still to be written. Its option keys")
    w("(prefix decided with the core's name) are added to this table as each one lands.\n")

    def row(i):
        s, c, note = mapping[i]
        where = infos.get(i, "")
        found = ", ".join(short[x] for x, _ in SHORT if x in have[i])
        return f"| `{i}` | {where} | {found} | {STATUS[s]} | {note} |"

    for cat, title in CATS:
        ids = sorted(i for i, (s, c, _) in mapping.items() if s == "core" and c == cat)
        w(f"## {title}: planned in our core ({len(ids)})\n")
        w("| Setting | Dolphin keeps it in | Found in | Ours | Note |")
        w("|---|---|---|---|---|")
        out.extend(row(i) for i in ids)
        w("")
    for s, title in (("app", "Done by the app for every console"), ("app-gap", "Belongs in the app, not there yet"),
                     ("na", "Does not apply on an iPhone")):
        ids = sorted(i for i, (st, _, _) in mapping.items() if st == s)
        w(f"## {title} ({len(ids)})\n")
        w("| Setting | Dolphin keeps it in | Found in | Ours | Note |")
        w("|---|---|---|---|---|")
        out.extend(row(i) for i in ids)
        w("")
    open(OUT, "w").write("\n".join(out))
    print(f"{len(have)} settings; {dict(counts)}; wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
